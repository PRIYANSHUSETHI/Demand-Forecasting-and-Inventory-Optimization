def simulate_inventory_policy(demand, reorder_point, order_qty, init_inv=1000):
    inventory = init_inv
    stockouts = 0
    for d in demand:
        if inventory < d:
            stockouts += 1
        inventory -= d
        if inventory <= reorder_point:
            inventory += order_qty
    return stockouts

