def simulate_stock_behavior(demand_series, inventory=1000, reorder_point=400, order_qty=600):
    stockouts = 0
    overstock_days = 0
    daily_inventory = []

    for demand in demand_series:
        if inventory < demand:
            stockouts += 1
        inventory -= demand
        if inventory <= reorder_point:
            inventory += order_qty
        if inventory > 1500:  # Threshold for overstock
            overstock_days += 1
        daily_inventory.append(inventory)

    return stockouts, overstock_days, daily_inventory

